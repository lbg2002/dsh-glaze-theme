import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const libDir = path.join(root, 'lib')

const CLIENT_ORDER = [
  'palette.mjs',
  'fonts.mjs',
  'defaults.mjs',
  'tokens.mjs',
  'styles.mjs',
  'appearance.mjs',
  'image-util.mjs',
  'ui.mjs',
  'entry.mjs',
]

function transformModuleToScriptPart(source, filename) {
  let code = source
    // Strip multi-line and single-line relative imports from ./foo.mjs
    .replace(/^import\s+[\s\S]*?\s+from\s+['"]\.\/[^'"]+['"]\s*;?\s*$/gm, '')
    // Strip `export ` prefixes on declarations
    .replace(/^export\s+(?=(?:async\s+)?function\b|const\b|let\b|var\b|class\b)/gm, '')
  return `// ── ${filename} ──────────────────────────────────────────────\n${code.trim()}\n`
}

export function buildAll() {
  mkdirSync(libDir, { recursive: true })

  // 1. Copy Node entry
  const srcNode = path.join(root, 'src', 'index.mjs')
  const dstNode = path.join(libDir, 'index.js')
  copyFileSync(srcNode, dstNode)

  // 2. Bundle client entry into a self-contained IIFE script
  const parts = CLIENT_ORDER.map((file) => {
    const raw = readFileSync(path.join(root, 'src', 'client', file), 'utf8')
    return transformModuleToScriptPart(raw, file)
  })

  const bundled = [
    '/* Auto-generated by scripts/build.mjs — do not edit lib/client.js directly. */',
    ';(function () {',
    "'use strict';",
    ...parts,
    '})();',
    '',
  ].join('\n')

  // Syntax-check generated bundle
  new vm.Script(bundled, { filename: 'lib/client.js' })

  const dstClient = path.join(libDir, 'client.js')
  writeFileSync(dstClient, bundled, 'utf8')

  return {
    nodeBytes: readFileSync(dstNode).byteLength,
    clientBytes: Buffer.byteLength(bundled, 'utf8'),
  }
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const stats = buildAll()
  console.log(`Built dsh-glaze-theme: lib/index.js (${stats.nodeBytes} B), lib/client.js (${stats.clientBytes} B)`)
}
